use crate::framebuffer::{Color, Framebuffer};

pub fn draw_glyph(
    framebuffer: &mut Framebuffer,
    x: i32,
    y: i32,
    byte: u8,
    color: Color,
    scale: i32,
) {
    let rows = glyph(byte.to_ascii_uppercase());
    for (row, bits) in rows.iter().enumerate() {
        for column in 0..5 {
            if bits & (1 << (4 - column)) != 0 {
                framebuffer.rect(
                    x + column * scale,
                    y + row as i32 * scale,
                    scale,
                    scale,
                    color,
                );
            }
        }
    }
}

